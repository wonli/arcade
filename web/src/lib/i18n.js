export function normalizeLocale(locale) {
  const value = String(locale ?? '').trim().toLowerCase()
  return value.startsWith('zh') ? 'zh-CN' : DEFAULT_LOCALE
}

export function createTranslator(locale = DEFAULT_LOCALE, catalog = MESSAGES) {
  const normalized = normalizeLocale(locale)
  return (key, values = {}) => {
    let text = catalog[normalized]?.[key] ?? catalog[DEFAULT_LOCALE]?.[key] ?? key
    for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value))
    return text
  }
}

export function readStoredLocale(storage = typeof localStorage === 'undefined' ? null : localStorage) {
  try { return normalizeLocale(storage?.getItem?.(LOCALE_STORAGE_KEY)) }
  catch { return DEFAULT_LOCALE }
}

export function storeLocale(locale, storage = typeof localStorage === 'undefined' ? null : localStorage) {
  const normalized = normalizeLocale(locale)
  try { storage?.setItem?.(LOCALE_STORAGE_KEY, normalized) } catch {}
  return normalized
}
